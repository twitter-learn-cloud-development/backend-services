// Explicit --live: creates isolated users + one public tweet, calls the real model twice.
// Credentials stay in one ephemeral browser context and are never included in reports.
const assert = require('node:assert/strict');
const crypto = require('node:crypto');
const fs = require('node:fs/promises');
const path = require('node:path');
const { chromium } = require(path.join(process.env.PLAYWRIGHT_MODULE_DIR, 'playwright'));

async function main() {
  assert(process.argv.includes('--live'), 'Pass --live to authorize isolated test data and model calls');
  const artifacts = path.resolve(__dirname, '../artifacts');
  await fs.mkdir(artifacts, { recursive: true });
  const browser = await chromium.launch({ channel: 'msedge', headless: true });
  const context = await browser.newContext({ viewport: { width: 1440, height: 900 }, locale: 'zh-CN', timezoneId: 'Asia/Shanghai' });
  const run = crypto.randomBytes(5).toString('hex');
  const report = { run, checks: [], retained: { users: 0, tweets: 0 }, modelQuestions: 0 };
  const gateway = 'http://127.0.0.1:9638';
  const credentials = { username: `sw${run}`, email: `sw${run}@example.com`, password: crypto.randomBytes(24).toString('base64url') };
  try {
    const registered = await context.request.post(`${gateway}/api/v1/auth/register`, { data: credentials });
    assert.equal(registered.status(), 200, 'register isolated widget test user');
    report.retained.users++;
    const page = await context.newPage();
    const pageErrors = [];
    page.on('pageerror', error => pageErrors.push(error.message));
    await page.goto('http://localhost:5173/login');
    await page.getByRole('button', { name: '打开小栖客服', exact: true }).click();
    const panel = page.frameLocator('iframe[title="小栖客服对话"]');
    await panel.getByRole('button', { name: '登录现有账号后咨询' }).waitFor();
    assert.equal(await panel.locator('.mini-message').count(), 0);
    await page.getByRole('button', { name: '收起小栖客服', exact: true }).click();
    await page.locator('#email').fill(credentials.email);
    await page.locator('#password').fill(credentials.password);
    await page.locator('button[type="submit"]').click();
    await page.waitForURL('http://localhost:5173/');
    const token = await page.evaluate(() => localStorage.getItem('token'));
    assert(token, 'real web login returns an authenticated session');
    const tweetText = `小栖引用端到端测试 ${run}`;
    const created = await context.request.post(`${gateway}/api/v1/tweets`, { headers: { Authorization: `Bearer ${token}` }, data: { content: tweetText, media_urls: [] } });
    assert.equal(created.status(), 201, 'create one isolated test tweet');
    report.retained.tweets++;
    const tweetId = String((await created.json()).tweet.id);
    assert.match(tweetId, /^[0-9]+$/);
    await page.getByRole('button', { name: '打开小栖客服', exact: true }).click();
    await panel.getByText(`已连接 @${credentials.username}`, { exact: true }).waitFor();
    report.checks.push('real-login-and-host-session');
    await panel.getByRole('textbox', { name: '客服问题' }).fill('请用中文逐条列出我最近发布内容的编号、发布时间和可见性');
    const firstWait = page.waitForResponse(response => response.url().includes('/api/v1/support/chat') && response.request().method() === 'POST', { timeout: 130000 });
    await panel.getByRole('button', { name: '发送客服问题' }).click();
    const firstResponse = await firstWait;
    assert.equal(firstResponse.status(), 200, 'real recent-content chat');
    report.modelQuestions++;
    const first = await firstResponse.json();
    assert.equal(first.citations.length, 1, 'one real record, no invented links');
    assert.equal(first.citations[0].id, `tweet:${tweetId}`);
    assert.equal(first.citations[0].path, `/tweets/${tweetId}`);
    assert(first.evidence_refs.includes(first.citations[0].evidence_ref));
    assert(first.answer.includes(`tweet:${tweetId}`));
    assert(!first.answer.includes('58706'));
    const firstRequest = firstResponse.request();
    const replay = await context.request.post('http://127.0.0.1:8000/api/v1/support/chat', { headers: { Authorization: `Bearer ${token}`, 'Idempotency-Key': firstRequest.headers()['idempotency-key'] }, data: firstRequest.postDataJSON() });
    assert.equal(replay.status(), 200);
    assert.deepEqual((await replay.json()).citations, first.citations);
    report.checks.push('verified-tweet-citation-and-idempotent-replay');
    const frameBefore = page.frames().find(frame => frame.url().includes('embed=1'));
    await panel.getByRole('link', { name: first.citations[0].label + ' ↗', exact: true }).click();
    await page.waitForURL(`http://localhost:5173/tweets/${tweetId}`);
    await page.getByText(tweetText, { exact: true }).waitFor();
    assert.equal(page.frames().find(frame => frame.url().includes('embed=1')), frameBefore, 'route navigation keeps iframe mounted');
    assert.equal(await panel.locator('.mini-message.assistant').count(), 1);
    report.checks.push('citation-opens-real-tweet-without-losing-chat');
    await panel.getByRole('textbox', { name: '客服问题' }).fill('收起后保留的草稿');
    await page.getByRole('button', { name: '收起小栖客服', exact: true }).click();
    await page.getByRole('button', { name: '打开小栖客服', exact: true }).click();
    assert.equal(await panel.getByRole('textbox', { name: '客服问题' }).inputValue(), '收起后保留的草稿');
    report.checks.push('minimize-preserves-draft-and-conversation');
    await panel.getByRole('textbox', { name: '客服问题' }).fill('Workflow 是什么？请按本项目的使用指南说明如何创建、保存和运行，并解释保存和发布给 Agent 的区别。');
    const helpWait = page.waitForResponse(response => response.url().includes('/api/v1/support/chat') && response.request().method() === 'POST', { timeout: 130000 });
    await panel.getByRole('button', { name: '发送客服问题' }).click();
    const helpResponse = await helpWait;
    assert.equal(helpResponse.status(), 200, 'real Workflow help chat');
    report.modelQuestions++;
    const help = await helpResponse.json();
    assert.equal(help.conversation_id, first.conversation_id, 'continuation reuses conversation');
    assert(help.evidence_refs.some(ref => ref.startsWith('ev_knowledge_')), 'help has published knowledge evidence');
    assert(/Workflow|工作流/.test(help.answer) && /保存/.test(help.answer) && /运行/.test(help.answer));
    assert.equal(help.citations.length, 0, 'help text must not invent tweet links');
    report.checks.push('workflow-rag-help-and-continuation');
    await page.screenshot({ path: path.join(artifacts, 'live-widget-desktop.png') });
    await page.setViewportSize({ width: 390, height: 844 });
    const bounds = await page.locator('.xiaoqi-panel').boundingBox();
    assert(bounds && bounds.x >= 0 && bounds.x + bounds.width <= 390 && bounds.y >= 0);
    await page.screenshot({ path: path.join(artifacts, 'live-widget-mobile.png') });
    report.checks.push('mobile-panel-fits-viewport');
    const other = { username: `sw${run}b`, email: `sw${run}b@example.com`, password: crypto.randomBytes(24).toString('base64url') };
    assert.equal((await context.request.post(`${gateway}/api/v1/auth/register`, { data: other })).status(), 200);
    report.retained.users++;
    const otherLogin = await context.request.post(`${gateway}/api/v1/auth/login`, { data: { email: other.email, password: other.password } });
    assert.equal(otherLogin.status(), 200);
    const otherToken = (await otherLogin.json()).token;
    const forbidden = await context.request.post('http://127.0.0.1:8000/api/v1/support/chat', { headers: { Authorization: `Bearer ${otherToken}`, 'Idempotency-Key': crypto.randomUUID() }, data: { conversation_id: first.conversation_id, message: '查看其他人的会话' } });
    assert.equal(forbidden.status(), 403);
    const anonymous = await context.request.post('http://127.0.0.1:8000/api/v1/support/chat', { headers: { 'Idempotency-Key': crypto.randomUUID() }, data: { message: '未登录请求' } });
    assert.equal(anonymous.status(), 401);
    report.checks.push('cross-user-403-and-anonymous-401');
    assert.deepEqual(pageErrors, [], 'no uncaught browser exceptions');
    report.status = 'passed';
    report.answers = { recent: first.answer, workflow: help.answer };
  } catch (error) {
    report.status = 'failed';
    report.error = error.message;
    throw error;
  } finally {
    await fs.writeFile(path.join(artifacts, 'live-widget-report.json'), JSON.stringify(report, null, 2));
    console.log(JSON.stringify({ ...report, answers: undefined }));
    await context.close();
    await browser.close();
  }
}
main().catch(error => { console.error(error.message); process.exitCode = 1; });
